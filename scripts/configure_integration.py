#!/usr/bin/env python3
"""Generate public deployment settings and native SmartThings references.

Run after editing integration.json, or use --namespace to change its namespace.
Only deployment fields are updated; application source and capability contracts
are never rewritten. A namespace change clears affected presentation IDs, which
must be regenerated by deploying the native UI to the destination account.
"""
import argparse
import ast
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DRIVERS = ("xiaomi-miio", "tuya-local")
PYTHON_DIRS = (
    "tuya-local/bridge",
    "notification-service",
    "smartthings/device-configs",
)
NOTICE = "Generated by scripts/configure_integration.py; edit integration.json"
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9_]*\Z")
PACKAGE_KEY = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\Z")


def validate(config):
    if not isinstance(config, dict):
        raise ValueError("integration.json must contain an object")
    namespace = config.get("namespace")
    if not isinstance(namespace, str) or not IDENTIFIER.fullmatch(namespace):
        raise ValueError("namespace must be a nonempty identifier without dots")
    package_keys = config.get("package_keys")
    if not isinstance(package_keys, dict):
        raise ValueError("package_keys must contain both driver package keys")
    for driver in DRIVERS:
        key = package_keys.get(driver)
        if not isinstance(key, str) or not PACKAGE_KEY.fullmatch(key):
            raise ValueError("Invalid package key for " + driver)
    support_url = config.get("support_url")
    if not isinstance(support_url, str) or any(c.isspace() for c in support_url):
        raise ValueError("support_url must be a public HTTP(S) URL")
    parsed = urlsplit(support_url)
    if (parsed.scheme not in {"http", "https"} or not parsed.hostname
            or parsed.username is not None or parsed.password is not None):
        raise ValueError("support_url must be a public HTTP(S) URL without credentials")


def previous_namespaces(root, config_namespace):
    """Read generated constants without executing modules from the checkout."""
    result = {config_namespace}
    for directory in PYTHON_DIRS:
        path = root / directory / "integration_settings.py"
        if not path.exists():
            continue
        try:
            module = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue  # A damaged generated module is replaced below.
        for statement in module.body:
            if (isinstance(statement, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "NAMESPACE"
                            for target in statement.targets)
                    and isinstance(statement.value, ast.Constant)
                    and isinstance(statement.value.value, str)
                    and IDENTIFIER.fullmatch(statement.value.value)):
                result.add(statement.value.value)
    return result


def capability_id(value, old_namespaces, namespace):
    if isinstance(value, str):
        prefix, separator, name = value.partition(".")
        if separator and prefix in old_namespaces and IDENTIFIER.fullmatch(name):
            return namespace + "." + name
    return value


def update_profile(text, old_namespaces, namespace):
    """Update only capability list IDs, retaining comments and YAML formatting."""
    lines = text.splitlines(keepends=True)
    capability_indent = None
    changed_namespace = False
    for index, line in enumerate(lines):
        stripped = line.lstrip()
        indent = len(line) - len(stripped)
        if stripped.strip() == "capabilities:":
            capability_indent = indent
            continue
        if not stripped.strip() or stripped.startswith("#"):
            continue
        if capability_indent is None:
            continue
        if indent <= capability_indent:
            capability_indent = None
            continue
        match = re.fullmatch(r"(\s*-\s+id:\s*)([\"']?)([\w.]+)\2([^\r\n]*)(\r?\n)?", line)
        if not match:
            continue
        new_id = capability_id(match[3], old_namespaces, namespace)
        if new_id != match[3]:
            lines[index] = match[1] + match[2] + new_id + match[2] + match[4] + (match[5] or "")
            changed_namespace = True
    if changed_namespace:
        # The UI ID belongs to its original capability IDs/account. Preserve
        # other metadata, but never carry that presentation to a new namespace.
        metadata_indent = None
        retained = []
        for line in lines:
            stripped = line.lstrip()
            indent = len(line) - len(stripped)
            if stripped.strip() == "metadata:":
                metadata_indent = indent
            elif stripped.strip() and not stripped.startswith("#"):
                if metadata_indent is not None and indent <= metadata_indent:
                    metadata_indent = None
                if metadata_indent is not None and stripped.startswith("vid:"):
                    continue
            retained.append(line)
        lines = retained
    return "".join(lines)


def update_json(value, old_namespaces, namespace):
    if isinstance(value, list):
        return [update_json(item, old_namespaces, namespace) for item in value]
    if isinstance(value, dict):
        return {key: (capability_id(item, old_namespaces, namespace)
                      if key in {"capability", "capabilityId"}
                      else update_json(item, old_namespaces, namespace))
                for key, item in value.items()}
    return value


def python_settings(config):
    return (f'"""{NOTICE}."""\n'
            f'NAMESPACE = {config["namespace"]!r}\n'
            '\n\n'
            'def capability(name):\n'
            '    return NAMESPACE + "." + name\n')


def lua_settings(config):
    return (f'-- {NOTICE}.\n'
            f'local namespace = {json.dumps(config["namespace"])}\n'
            'return {\n'
            '  namespace = namespace,\n'
            '  capability = function(name) return namespace .. "." .. name end,\n'
            '}\n')


def planned_updates(root=ROOT, namespace=None):
    root = Path(root)
    config_path = root / "integration.json"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    validate(config)
    old_namespaces = previous_namespaces(root, config["namespace"])
    if namespace is not None:
        config["namespace"] = namespace
    validate(config)
    namespace = config["namespace"]
    desired = {config_path: json.dumps(config, ensure_ascii=False, indent=2) + "\n"}
    for directory in PYTHON_DIRS:
        desired[root / directory / "integration_settings.py"] = python_settings(config)
    for driver in DRIVERS:
        directory = root / driver
        desired[directory / "src/integration_settings.lua"] = lua_settings(config)
        config_text = (directory / "config.yml").read_text(encoding="utf-8")
        for field, value in (("packageKey", config["package_keys"][driver]),
                             ("vendorSupportInformation", config["support_url"])):
            config_text, count = re.subn(
                rf"^{field}:.*$", lambda _match: field + ": " + json.dumps(value), config_text,
                flags=re.MULTILINE)
            if count != 1:
                raise ValueError(f"{driver}/config.yml must define exactly one {field}")
        desired[directory / "config.yml"] = config_text
        for path in sorted((directory / "profiles").glob("*.yml")):
            desired[path] = update_profile(path.read_text(encoding="utf-8"), old_namespaces, namespace)
    for directory in (root / "smartthings", root / "tuya-local"):
        for folder in ("device-configs", "capabilities", "translations"):
            for path in sorted((directory / folder).glob("*.json")):
                original = path.read_text(encoding="utf-8")
                value = json.loads(original)
                updated = update_json(value, old_namespaces, namespace)
                if folder == "capabilities" and isinstance(updated, dict) and "id" in updated:
                    updated["id"] = capability_id(updated["id"], old_namespaces, namespace)
                desired[path] = (original if updated == value else
                                 json.dumps(updated, ensure_ascii=False, indent=2) + "\n")
    return {path: value for path, value in desired.items()
            if not path.exists() or path.read_text(encoding="utf-8") != value}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--namespace", help="Set and persist the destination capability namespace")
    parser.add_argument("--check", action="store_true", help="Report stale generated settings without writing")
    args = parser.parse_args(argv)
    try:
        updates = planned_updates(namespace=args.namespace)
    except (OSError, ValueError) as error:
        parser.exit(2, str(error) + "\n")
    for path, value in updates.items():
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8")
        print(("stale: " if args.check else "updated: ") + str(path.relative_to(ROOT)))
    if args.check and updates:
        return 1
    print("Integration settings are consistent." if not updates else "Integration settings generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
